class _Stub:
    """Placeholder for any non-numpy class inside the pickle.

    The processed_data.pkl files carry a fitted MinMaxScaler and a
    LabelEncoder.  We never touch either, and instantiating this stub in their
    place means unpickling does not import scikit-learn at all -- no estimator
    is ever constructed, which is exactly what the no-compute constraint asks
    for.
    """

    def __init__(self, *args, **kwargs):
        pass

    def __setstate__(self, state):
        pass


class _RestrictedUnpickler(pickle.Unpickler):
    def find_class(self, module, name):
        if module.startswith("numpy") or module == "builtins":
            return super().find_class(module, name)
        return _Stub


def load_split_info(ds_dir: str) -> dict:
    """n_train, n_test, n_features and class counts from processed_data.pkl.

    Reads y_train / y_test / X_train.shape and nothing else.
    """
    path = C.REPO / ds_dir / "data" / "processed_data.pkl"
    with open(path, "rb") as fh:
        blob = _RestrictedUnpickler(fh).load()

    y_tr = np.asarray(blob["y_train"]).ravel()
    y_te = np.asarray(blob["y_test"]).ravel()
    x_tr = np.asarray(blob["X_train"])
    x_te = np.asarray(blob["X_test"])

    def counts(y):
        return {str(k): int(v) for k, v in sorted(Counter(y.tolist()).items())}

    all_counts = Counter(y_tr.tolist()) + Counter(y_te.tolist())
    return {
        "dataset_dir": ds_dir,
        "n_train": int(x_tr.shape[0]),
        "n_test": int(x_te.shape[0]),
        "n_features": int(x_tr.shape[1]),
        "n_samples": int(x_tr.shape[0] + x_te.shape[0]),
        "n_classes": int(len(all_counts)),
        "class_counts_train": counts(y_tr),
        "class_counts_test": counts(y_te),
        "class_counts_all": {str(k): int(v) for k, v in sorted(all_counts.items())},
        "source": f"{ds_dir}/data/processed_data.pkl",
    }


def load_all_split_info() -> pd.DataFrame:
    return pd.DataFrame([load_split_info(d) for d in DATASET_DIRS])


# ==========================================================================
# Report JSONs -- globbed, because they sit at inconsistent depths
# ==========================================================================

def find_report(ds_dir: str, family: str, variant: str) -> Path | None:
    """Locate ``<std|dp>_<stem>_report.json`` for one (dataset, family).

    Globs beneath ``<DS>/<FAMILY_DIR>/`` at any depth, which covers
    ``BCP/RandomForest/`` (depth 2), ``BCP/LR/data/`` and
    ``*/SVM/output/`` (depth 3) alike.  Files prefixed ``old_`` are ignored,
    and the search is anchored on the model-family directory, so the stale
    duplicates under ``BCP/Result/data/`` are never picked up.
    """
    stem = SHORT_TO_STEM[family]
    root = C.REPO / ds_dir / SHORT_TO_DIR[family]
    if not root.is_dir():
        return None
    hits = [p for p in root.rglob(f"{variant}_{stem}_report.json")
            if not p.name.startswith("old_")]
    if not hits:
        return None
    # Deterministic when a family somehow has more than one: shallowest first.
    hits.sort(key=lambda p: (len(p.parts), str(p)))
    return hits[0]


def read_report(ds_dir: str, family: str, variant: str) -> dict | None:
    path = find_report(ds_dir, family, variant)
    if path is None:
        return None
    with open(path) as fh:
        data = json.load(fh)
    data["__path__"] = str(path.relative_to(C.REPO))
    return data


def rel(path: Path | str) -> str:
    """Repo-relative string for provenance columns."""
    return str(Path(path).resolve().relative_to(C.REPO))


# ==========================================================================
# Coverage report (stage 1 sanity check)
# ==========================================================================

def coverage_report() -> str:
    lines = []
    add = lines.append

    u = load_utility()
    m = load_mia()

    add("=" * 74)
    add("STAGE 1 COVERAGE REPORT")
    add("=" * 74)
    add(f"INCLUDE_LUNG_CANCER = {C.INCLUDE_LUNG_CANCER}   "
        f"UTILITY_LABEL = {C.UTILITY_LABEL!r}   RANDOM_FPR = {C.RANDOM_FPR}")
    add("")

    add(f"utility CSV  {C.UTILITY_CSV.relative_to(C.REPO)}  shape={u.shape}")
    add(f"  variants: {u['variant'].value_counts().to_dict()}")
    add(f"  datasets: {sorted(u['dataset'].unique())}")
    add(f"  models:   {sorted(u['model'].unique())}")
    dp = u[u["variant"] == "dp"]
    add(f"  DP rows with n_runs==30: {int((dp['n_runs'] == 30).sum())} / {len(dp)}")
    add(f"  DP rows with n_runs NaN: {int(dp['n_runs'].isna().sum())}")
    nrun_missing = (dp[dp["n_runs"].isna()]
                    .groupby(["dataset", "model"]).size().to_dict())
    add(f"    -> missing n_runs by (dataset, model): {nrun_missing}")
    add(f"  exported_model_accuracy blank on {int(dp['exported_model_accuracy'].isna().sum())} DP rows")
    blank = (dp[dp["exported_model_accuracy"].isna()]
             .groupby(["dataset", "model"]).size().to_dict())
    add(f"    -> {blank}")
    add("")

    add(f"MIA CSV      {C.MIA_CSV.relative_to(C.REPO)}  shape={m.shape}")
    add(f"  attack x variant: {m.groupby(['attack', 'variant']).size().to_dict()}")
    add(f"  models:   {sorted(m['model'].unique())}")
    add(f"  DP epsilon grid: {sorted(m[m['variant'] == 'dp']['epsilon'].unique())}")
    for attack in ("lira", "shokri", "yeom"):
        sub = m[m["attack"] == attack]
        nm = sub["n_members"].notna().sum()
        add(f"  {attack:6s}: rows={len(sub):4d}  n_members present on {nm}")
    add("")

    add("Per-dataset attack CSV row counts (ground truth):")
    for attack in ("lira", "shokri", "yeom"):
        counts = {}
        for d in DATASET_DIRS:
            try:
                counts[d] = len(load_attack_csv(attack, d))
            except FileNotFoundError:
                counts[d] = "MISSING"
        add(f"  {attack:6s}: {counts}")
    add("")

    add("Baseline (standard) join: 6 datasets x 5 families = 30 pairs")
    std_u = u[u["variant"] == "standard"]
    add(f"  utility standard rows: {len(std_u)}")
    for attack in ("lira", "shokri", "yeom"):
        std_m = m[(m["attack"] == attack) & (m["variant"] == "standard")]
        add(f"  {attack:6s} standard rows: {len(std_m)}")
    add("")

    add("Split info from processed_data.pkl (class balance / n_train / n_test):")
    si = load_all_split_info()
    for r in si.itertuples():
        add(f"  {r.dataset_dir:14s} N={r.n_samples:6d} d={r.n_features:3d} "
            f"K={r.n_classes} train={r.n_train:6d} test={r.n_test:6d} "
            f"counts={r.class_counts_all}")
    add("")

    add("Report JSON discovery (std / dp per dataset x family):")
    for d in DATASET_DIRS:
        row = []
        for f in FAMILIES:
            s = find_report(d, f, "std")
            p = find_report(d, f, "dp")
            row.append(f"{f}:{'S' if s else '-'}{'D' if p else '-'}")
        add(f"  {d:14s} {' '.join(row)}")
    add("")

    add("Reused analysis inputs:")
    for name, fn in [("d14_summary", load_within_pair_summary),
                     ("d14_pair_correlations", load_within_pair_correlations),
                     ("d15_rho_by_epsilon", load_rho_by_epsilon),
                     ("d15_robustness_excluded", load_robustness_excluded),
                     ("d15_balanced_accuracy", load_balanced_accuracy),
                     ("d15_majority_class_accuracy", load_majority_class_accuracy),
                     ("d16_figure_input", load_figure_input),
                     ("d16_correlations", load_correlations)]:
        add(f"  {name:30s} shape={fn().shape}")
    add("")

    add("LiRA log-log ROC PNGs:")
    for d in DATASET_DIRS:
        p = C.REPO / LIRA_ROC_PNG.format(ds=d)
        add(f"  {d:14s} {'present' if p.exists() else 'MISSING'}  {p.relative_to(C.REPO)}")
    add("=" * 74)
    return "\n".join(lines)


if __name__ == "__main__":
    print(coverage_report())
