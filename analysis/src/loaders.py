def filter_datasets(df: pd.DataFrame, col: str = "dataset") -> pd.DataFrame:
    """Drop Lung Cancer rows when the switch is off. ``col`` may hold either
    the display name or the directory name."""
    if C.INCLUDE_LUNG_CANCER:
        return df
    bad = {"Lung Cancer", "LUNG_CANCER"}
    return df[~df[col].isin(bad)].copy()


