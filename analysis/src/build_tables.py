_ESCAPE = {
    "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    # Greek letters are written plainly in the CSVs (CLAUDE.md S11) and become
    # proper math on the way into LaTeX.
    "\u03b5": r"$\varepsilon$", "\u03b4": r"$\delta$", "\u0394": r"$\Delta$",
    "\u03c1": r"$\rho$",
}


def tex_escape(text: str) -> str:
    """Escape a plain-text cell for LaTeX.

    Cells are escaped unconditionally; anything that must reach LaTeX as markup
    (URLs, math, significance stars) is declared via ``raw_columns`` on
    ``write_table`` instead of being sniffed out of the string, which is what
    previously mangled ``$N$`` into ``\\$N\\$``.
    """
    return "".join(_ESCAPE.get(ch, ch) for ch in str(text))


def fmt(value, nd: int = 4, raw: bool = False) -> str:
    """Format a cell for LaTeX. Missing/conflict markers survive verbatim."""
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return C.MISSING.format(what="value absent from source")
    if isinstance(value, str):
        return value if raw else tex_escape(value)
    if isinstance(value, (int, np.integer)):
        return f"{int(value):,}"
    return f"{float(value):.{nd}f}"


def write_table(name: str, df: pd.DataFrame, caption: str, note: str,
                col_spec: str | None = None, nd: int = 4,
                tex_columns: list[str] | None = None,
                headers: dict[str, str] | None = None,
                tex_df: pd.DataFrame | None = None,
                raw_columns: set[str] | None = None) -> None:
    """Write ``tables/csv/<name>.csv`` and ``tables/tex/<name>.tex``.

    ``df`` is always what lands in the CSV.  ``tex_df`` lets a table present a
    different *rendering* of the same values in LaTeX (URL macros, significance
    stars); it never introduces a value that is not in ``df``.
    """
    C.TABLES_CSV.mkdir(parents=True, exist_ok=True)
    C.TABLES_TEX.mkdir(parents=True, exist_ok=True)
    df.to_csv(C.TABLES_CSV / f"{name}.csv", index=False)

    base = tex_df if tex_df is not None else df
    tdf = base[tex_columns] if tex_columns else base
    headers = headers or {}
    raw_columns = raw_columns or set()
    spec = col_spec or "l" * len(tdf.columns)

    lines = []
    env = "table"
    lines.append("%% Auto-generated by analysis/src/build_tables.py -- do not edit by hand.")
    lines.append("%% MDPI booktabs fragment; \\input{} it from the manuscript.")
    lines.append("%% Requires: booktabs, url. No document preamble here.")
    lines.append(f"\\begin{{{env}}}[H]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append(f"\\caption{{{caption}}}")
    lines.append(f"\\label{{tab:{name}}}")
    lines.append(f"\\begin{{tabular}}{{{spec}}}")
    lines.append("\\toprule")
    # Headers are authored in this file, so they are already valid LaTeX and
    # pass through verbatim; only a bare column name needs escaping.
    head = " & ".join(headers[c] if c in headers
                      else (c if "$" in c or "\\" in c else tex_escape(c))
                      for c in tdf.columns)
    lines.append(head + r" \\")
    lines.append("\\midrule")
    for _, row in tdf.iterrows():
        lines.append(" & ".join(fmt(row[c], nd, raw=c in raw_columns)
                                for c in tdf.columns) + r" \\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    full_note = note
    if not C.INCLUDE_LUNG_CANCER:
        full_note += " " + C.LUNG_CANCER_EXCLUSION_REASON
    lines.append(f"\\begin{{tablenotes}}\n\\footnotesize\n{full_note}\n\\end{{tablenotes}}")
    lines.append(f"\\end{{{env}}}")
    (C.TABLES_TEX / f"{name}.tex").write_text("\n".join(lines) + "\n")
    print(f"  wrote tables/csv/{name}.csv and tables/tex/{name}.tex  ({len(df)} rows)")


