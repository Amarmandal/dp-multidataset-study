def t_rho_by_epsilon(conflicts: list) -> pd.DataFrame:
    src = L.load_rho_by_epsilon()
    eps = sorted(src["epsilon"].unique())
    rows = []
    for (subset, al, metric), grp in src.groupby(
            ["subset", "al_definition", "metric"], sort=False):
        g = grp.set_index("epsilon")
        row = {"subset": subset, "al_definition": al, "metric": metric,
               "n": int(g["n"].iloc[0])}
        for e in eps:
            if e in g.index:
                row[f"rho_eps_{e}"] = float(g.loc[e, "rho"])
                row[f"p_eps_{e}"] = float(g.loc[e, "p"])
            else:
                row[f"rho_eps_{e}"] = C.MISSING.format(what=f"rho at eps={e}")
                row[f"p_eps_{e}"] = C.MISSING.format(what=f"p at eps={e}")
        rows.append(row)
    return pd.DataFrame(rows)


def _rho_tex_view(df: pd.DataFrame) -> pd.DataFrame:
    """rho with a significance star, one column per epsilon."""
    eps = [c.replace("rho_eps_", "") for c in df.columns if c.startswith("rho_eps_")]
    out = {"subset": df["subset"], "al_definition": df["al_definition"],
           "metric": df["metric"], "n": df["n"]}
    for e in eps:
        r, p = df[f"rho_eps_{e}"], df[f"p_eps_{e}"]
        out[f"$\\varepsilon$={e}"] = [
            (v if isinstance(v, str)
             else f"{v:.3f}" + ("$^{*}$" if (not isinstance(q, str) and q < 0.05) else ""))
            for v, q in zip(r, p)]
    return pd.DataFrame(out)


